/* ESPN 对阵标题格式为「客队 at 主队」，逐队翻译后用「vs」连接；
   分队后只要有未命中映射的队名，仅回退该队为英文原样。 */
export function matchTitleZh(title: string): string {
  const separator = title.includes(' at ') ? ' at ' : ' vs '
  const sides = title.split(separator)
  if (sides.length !== 2) return title
  return `${teamZh(sides[0].trim())} vs ${teamZh(sides[1].trim())}`
}
